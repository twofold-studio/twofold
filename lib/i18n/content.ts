const bgWork: Work[] = work.map((item) => {
  const translation = projects[item.slug];
  if (!translation) throw new Error(`Missing Bulgarian project: ${item.slug}`);
  return {
    ...item,
    ...translation,
    images: item.images.map((image, i) => {
      const caption = translation.captions[i];
      if (!caption) throw new Error(`Missing Bulgarian image caption: ${item.slug}/${i}`);
      return { ...image, caption };
    }),
  };
});
