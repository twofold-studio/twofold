const bgWork: Work[] = work.map((item) => {
  const bulgarian = projects[item.slug];
  if (!bulgarian) throw new Error(`Missing Bulgarian project: ${item.slug}`);
  const { captions, linkLabel, ...translation } = bulgarian;
  return {
    ...item,
    ...translation,
    ...(item.link && { link: { ...item.link, label: linkLabel ?? item.link.label } }),
    images: item.images.map((image, i) => {
      const caption = captions[i];
      if (!caption) throw new Error(`Missing Bulgarian image caption: ${item.slug}/${i}`);
      return { ...image, caption };
    }),
  };
});
